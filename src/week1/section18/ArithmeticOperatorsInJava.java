package week1.section18;

public class ArithmeticOperatorsInJava {
    public static void main(String args[]) {
        char additionSymbol = '+';
        char subtractionSymbol = '-';
        char multiplicationSymbol = '*';
        char divisionSymbol = '/';
        char modulusSymbol = '%';

        System.out.println("+ (Addition) - Adds two values and returns the result.");
        System.out.println("- (Subtraction) - Subtracts one value from another and returns the result.");
        System.out.println("* (Multiplication) - Multiplies two values and returns the result.");
        System.out.println("/ (Division) - Divides one value by another and returns the result.");
        System.out.println("% (Modulus) - Returns the remainder when one value is divided by another.");
    }
}
