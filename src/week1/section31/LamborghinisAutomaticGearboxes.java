package week1.section31;

public class LamborghinisAutomaticGearboxes {
    public static void main(String[] args) {
        char upShiftSign = '+';
        System.out.printf("%c paddle, the gearbox will shift up to the next higher gear", upShiftSign);

        char downShiftSign = '-';
        System.out.printf("\n%c paddle will result in a downshift to a lower gear", downShiftSign);
    }
}
